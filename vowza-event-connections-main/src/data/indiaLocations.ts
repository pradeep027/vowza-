// Helper functions for cascading lookups
export function getStateNames(): string[] {
  return INDIA_STATES.map(s => s.name);
}

export function getDistrictsForState(stateName: string): DistrictData[] {
  const state = INDIA_STATES.find(s => s.name === stateName);
  return state ? state.districts : [];
}

export function getDistrictNames(stateName: string): string[] {
  return getDistrictsForState(stateName).map(d => d.name);
}

export function getTownsForDistrict(stateName: string, districtName: string): string[] {
  const districts = getDistrictsForState(stateName);
  const district = districts.find(d => d.name === districtName);
  return district ? district.towns : [];
}
